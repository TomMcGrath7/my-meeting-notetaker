// DropMemo — a thin SwiftUI front-end over scripts/process.sh.
//
// One window with a tab per memo: drag a recording in (or pick one), set who was
// in the meeting and the controls, and queue it. A Jobs tab lists every memo;
// queued memos run one at a time (one pipeline in RAM), each streaming its
// stdout into its own tab, and on success the out-dir is revealed in Finder
// with notes.md opened. It is deliberately NOT a
// reimplementation of the pipeline — every run shells out to scripts/process.sh
// (the single source of truth) so the app and the Voice Memos Shortcut behave
// identically.
//
// It also registers as a handler for .m4a/.wav/.mp3 (see Info.plist generated by
// scripts/build_dropmemo.sh), so "Open With ▸ DropMemo" and dropping a memo on
// the Dock icon both work.

import SwiftUI
import AppKit
import Darwin
import UniformTypeIdentifiers
import AVFoundation

// MARK: - Where the repo (and thus process.sh + config.yaml) lives

enum Repo {
    /// Resolution order: DROPMEMO_REPO env → Info.plist "DMRepoPath" (baked in
    /// at build time) → the checkout the .app is sitting in (build/DropMemo.app,
    /// so two levels up) → a sensible default. Keeps the .app relocatable while
    /// still finding the checkout it belongs to.
    ///
    /// Every candidate but the env var has to actually hold a scripts/process.sh
    /// to win. A baked path outlives the checkout being moved, and a stale one
    /// that points at where the repo used to be is worse than no bake at all —
    /// the app is usually inside the checkout that just moved with it.
    static var path: String {
        if let env = ProcessInfo.processInfo.environment["DROPMEMO_REPO"], !env.isEmpty {
            return (env as NSString).expandingTildeInPath
        }
        let baked = Bundle.main.object(forInfoDictionaryKey: "DMRepoPath") as? String
        // .../<repo>/build/DropMemo.app -> .../<repo>
        let alongside = Bundle.main.bundleURL
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .path
        let fallback = "~/GitHub/my-meeting-notetaker"
        for candidate in [baked, alongside, fallback] {
            guard let candidate = candidate, !candidate.isEmpty else { continue }
            let expanded = (candidate as NSString).expandingTildeInPath
            if FileManager.default.isExecutableFile(atPath: expanded + "/scripts/process.sh") {
                return expanded
            }
        }
        return (fallback as NSString).expandingTildeInPath
    }

    static var processSh: String { path + "/scripts/process.sh" }
    static var configPath: String { path + "/config.yaml" }
}

// MARK: - Controls

enum Backend: String, CaseIterable, Identifiable {
    case ollama = "Ollama"
    case claudeSub = "Claude (sub)"
    case anthropic = "Anthropic (API)"
    var id: String { rawValue }
    /// process.sh's LLM_BACKEND value.
    var llmBackend: String {
        switch self {
        case .ollama:    return "openai"
        case .claudeSub: return "claude-cli"   // local `claude` → subscription
        case .anthropic: return "anthropic"    // API key
        }
    }
}

enum DiarizeEngine: String, CaseIterable, Identifiable {
    case pyannote, sortformer
    var id: String { rawValue }
}

// MARK: - Job: one memo tab (its recording, roster and controls) + its run state

enum JobStatus: Equatable {
    case draft                 // being filled in; not in the queue
    case queued
    case running
    case done(outDir: String)
    case failed(status: Int32)
    case stopped

    var label: String {
        switch self {
        case .draft:   return "Draft"
        case .queued:  return "Queued"
        case .running: return "Running"
        case .done:    return "Done"
        case .failed:  return "Failed"
        case .stopped: return "Stopped"
        }
    }
    var isFinished: Bool {
        switch self {
        case .done, .failed, .stopped: return true
        default: return false
        }
    }
    var symbol: String {
        switch self {
        case .draft:   return "square.and.pencil"
        case .queued:  return "clock"
        case .running: return "gearshape.2"
        case .done:    return "checkmark.circle.fill"
        case .failed:  return "xmark.octagon.fill"
        case .stopped: return "stop.circle"
        }
    }
    var color: Color {
        switch self {
        case .done:    return .green
        case .failed:  return .red
        case .running: return .accentColor
        default:       return .secondary
        }
    }
}

@MainActor
final class Job: ObservableObject, Identifiable {
    let id = UUID()

    @Published var audioURL: URL?
    @Published var secondURL: URL?                    // optional: the same meeting, recorded on another device

    // Controls strip
    // Claude-sub by default: the two text steps are the ones that want a strong
    // model, and running them off-box costs this Mac no RAM. An 18 GB local
    // model beside an IDE and a VM is what took the machine down on 2026-08-27.
    @Published var backend: Backend = .claudeSub
    @Published var model: String = "sonnet"
    @Published var denoise = false
    @Published var diarize: DiarizeEngine = .pyannote
    @Published var asrModel: String = "1.7B"          // 0.6B = faster, 1.7B = accurate
    @Published var language: String = ""              // hint for speech ASR (blank = auto, right for a mixed memo)
    @Published var transcriptText: String = ""        // optional: paste a transcript to force-align
    @Published var transcriptURL: URL?                // …or attach one from a file (fallback)

    // Meeting roster — written to config.yaml right before this job runs (the
    // pipeline reads it to name speakers). Comma- or newline-separated names.
    @Published var participants: String = ""
    @Published var context: String = ""

    // The tab strip, the Jobs page and the queue counts observe JobQueue, not
    // each Job, so these two tell the queue when they change.
    @Published var status: JobStatus = .draft { didSet { JobQueue.shared.objectWillChange.send() } }
    @Published var isOpen = true { didSet { JobQueue.shared.objectWillChange.send() } }   // has a tab in the strip
    @Published var log: String = ""

    /// Drafts and queued jobs can still be edited: config.yaml and the flags
    /// are only built from these fields when the job starts.
    var isEditable: Bool { status == .draft || status == .queued }

    var title: String { audioURL?.lastPathComponent ?? "New memo" }

    var outDir: String? {
        if case .done(let out) = status { return out }
        return nil
    }

    /// A new tab takes over the previous tab's controls (backend, model, ASR…),
    /// but not its recording, transcript or roster: those belong to one meeting.
    func copyControls(from o: Job) {
        backend = o.backend; model = o.model; denoise = o.denoise
        diarize = o.diarize; asrModel = o.asrModel; language = o.language
    }

    /// Default model name to show when the backend toggles.
    func backendChanged() {
        switch backend {
        // qwen3:8b (~5 GB) rather than qwen3-coder:latest (18 GB) — the local
        // default has to fit beside whatever else is already open.
        case .ollama:    if model.isEmpty || model.contains("claude") || model.contains("sonnet") || model.contains("opus") { model = "qwen3:8b" }
        case .claudeSub: model = "sonnet"
        case .anthropic: if model.isEmpty || !model.contains("claude") { model = "claude-opus-4-8" }
        }
    }

    func accept(_ url: URL) {
        audioURL = url
        appendLine("• selected \(url.lastPathComponent)")
    }

    func acceptSecond(_ url: URL) {
        secondURL = url
        appendLine("• second recording: \(url.lastPathComponent)")
    }

    func append(_ s: String) { log += s }
    func appendLine(_ s: String) { log += s + "\n" }
}

// MARK: - Queue: owns every job and runs them one at a time

enum Tab: Hashable {
    case jobs
    case job(UUID)
}

@MainActor
final class JobQueue: ObservableObject {
    static let shared = JobQueue()

    @Published var jobs: [Job] = []
    @Published var selection: Tab = .jobs
    /// Set by Stop, so the next queued job doesn't start by itself the moment
    /// the stopped one exits. Resume clears it.
    @Published var paused = false

    /// While a context voice note is being transcribed its ASR model is in
    /// memory, so no pipeline starts until it is done.
    @Published var voiceNoteBusy = false {
        didSet { if !voiceNoteBusy { startNextIfIdle() } }
    }

    private var task: Process?
    @Published private(set) var current: Job?
    private var stopped = false

    init() {
        let first = Job()
        loadConfig(into: first)
        jobs = [first]
        selection = .job(first.id)
    }

    var openJobs: [Job] { jobs.filter(\.isOpen) }
    var isRunning: Bool { current != nil }
    var queuedCount: Int { jobs.filter { $0.status == .queued }.count }

    func job(_ id: UUID) -> Job? { jobs.first { $0.id == id } }

    var selectedJob: Job? {
        if case .job(let id) = selection { return job(id) }
        return nil
    }

    // MARK: tabs

    @discardableResult
    func newTab() -> Job {
        let j = Job()
        if let from = selectedJob ?? jobs.last { j.copyControls(from: from) }
        jobs.append(j)
        selection = .job(j.id)
        return j
    }

    func open(_ j: Job) {
        j.isOpen = true
        selection = .job(j.id)
    }

    /// Closing a draft's tab throws the draft away. Any other job only loses its
    /// tab and stays listed under Jobs.
    func close(_ j: Job) {
        if j.status == .draft {
            jobs.removeAll { $0.id == j.id }
        } else {
            j.isOpen = false
        }
        if selection == .job(j.id) {
            selection = openJobs.last.map { .job($0.id) } ?? .jobs
        }
    }

    /// Files from Finder "Open With", the Dock icon or the Share sheet: the
    /// first fills the current tab if it has no recording yet, the rest each get
    /// a tab of their own.
    func openFiles(_ urls: [URL]) {
        for url in urls {
            if let j = selectedJob, j.isEditable, j.audioURL == nil {
                j.accept(url)
            } else {
                newTab().accept(url)
            }
        }
    }

    // MARK: queue

    func enqueue(_ j: Job) {
        // A draft joins the queue; a finished job (done, failed, stopped) runs again.
        guard j.audioURL != nil, j.status == .draft || j.status.isFinished else { return }
        // Asking for this one memo when nothing else waits is a fresh start,
        // not a request to carry on the paused queue.
        if paused, current == nil, queuedCount == 0 { paused = false }
        j.status = .queued
        j.appendLine("• queued")
        startNextIfIdle()
    }

    /// Take a queued job out of the queue again (back to a draft).
    func unqueue(_ j: Job) {
        guard j.status == .queued else { return }
        j.status = .draft
        j.appendLine("• taken out of the queue")
    }

    func remove(_ j: Job) {
        guard j.status != .running else { return }
        jobs.removeAll { $0.id == j.id }
        if selection == .job(j.id) { selection = .jobs }
    }

    func clearFinished() {
        jobs.removeAll { $0.status.isFinished }
        if case .job(let id) = selection, job(id) == nil { selection = .jobs }
    }

    func resume() {
        paused = false
        startNextIfIdle()
    }

    /// The one place a run starts, so two pipelines (two ASR models, two LLMs)
    /// never sit in RAM at once.
    private func startNextIfIdle() {
        guard current == nil, !paused, !voiceNoteBusy,
              let next = jobs.first(where: { $0.status == .queued }) else { return }
        run(next)
    }

    // MARK: config.yaml <-> a job

    /// Minimal reader for the `participants:` list and `context: |` block this
    /// app writes (and the example file). Not a general YAML parser.
    func loadConfig(into j: Job) {
        guard let text = try? String(contentsOfFile: Repo.configPath, encoding: .utf8) else { return }
        var names: [String] = []
        var ctx: [String] = []
        var inCtx = false
        for raw in text.components(separatedBy: "\n") {
            if inCtx {
                if raw.hasPrefix("  ") { ctx.append(String(raw.dropFirst(2))); continue }
                if raw.trimmingCharacters(in: .whitespaces).isEmpty { ctx.append(""); continue }
                inCtx = false
            }
            let t = raw.trimmingCharacters(in: .whitespaces)
            if t.hasPrefix("- ") {
                names.append(String(t.dropFirst(2)).trimmingCharacters(in: .whitespaces))
            } else if t.hasPrefix("context:") {
                inCtx = true
            }
        }
        if !names.isEmpty { j.participants = names.joined(separator: ", ") }
        let c = ctx.joined(separator: "\n").trimmingCharacters(in: .whitespacesAndNewlines)
        if !c.isEmpty { j.context = c }
    }

    /// Write a job's roster to config.yaml so the pipeline picks it up. Called
    /// right before that job starts, and only one job runs at a time, so each
    /// run reads its own roster.
    private func writeConfig(_ j: Job) {
        let names = j.participants
            .split(whereSeparator: { $0 == "," || $0 == "\n" })
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .filter { !$0.isEmpty }
        var y = "# Written by DropMemo. Edit here or in the app.\nparticipants:\n"
        for n in names { y += "  - \(n)\n" }
        let ctx = j.context.trimmingCharacters(in: .whitespacesAndNewlines)
        if !ctx.isEmpty {
            y += "context: |\n"
            for line in ctx.components(separatedBy: "\n") { y += "  \(line)\n" }
        }
        try? y.write(toFile: Repo.configPath, atomically: true, encoding: .utf8)
    }

    // MARK: run

    private func run(_ j: Job) {
        guard let audio = j.audioURL else { j.status = .draft; startNextIfIdle(); return }
        guard FileManager.default.isExecutableFile(atPath: Repo.processSh) else {
            j.appendLine("✗ can't find process.sh at \(Repo.processSh)")
            j.appendLine("  Set DROPMEMO_REPO, or rebuild so DMRepoPath points at your checkout.")
            j.status = .failed(status: -1)
            startNextIfIdle()
            return
        }

        writeConfig(j)           // this job's roster → config.yaml before the run
        j.log = ""
        j.status = .running
        current = j
        stopped = false

        // Map the controls onto process.sh's interface.
        var args = [Repo.processSh, audio.path]
        var env = ProcessInfo.processInfo.environment
        env["LLM_BACKEND"] = j.backend.llmBackend
        switch j.backend {
        case .ollama:
            env["OLLAMA_MODEL"] = j.model            // process.sh passes this as --model-llm
        case .claudeSub, .anthropic:
            args += ["--model-llm", j.model]         // model id/alias is a pass-through flag
        }
        if j.denoise { args.append("--denoise") }
        args += ["--diarize-engine", j.diarize.rawValue]
        args += ["--model", j.asrModel]              // ASR/align size (0.6B|1.7B)
        let lang = j.language.trimmingCharacters(in: .whitespaces)
        if !lang.isEmpty { args += ["--language", lang] }
        // Optional transcript to force-align (e.g. a Voice Memos export). Pasted
        // text wins over an attached file; write it to a temp file for
        // --transcript, one per job so a queued job's text isn't overwritten.
        if !j.transcriptText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let dir = FileManager.default.temporaryDirectory.appendingPathComponent("DropMemo", isDirectory: true)
            try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            let f = dir.appendingPathComponent("pasted-transcript-\(j.id.uuidString).txt")
            if (try? j.transcriptText.write(to: f, atomically: true, encoding: .utf8)) != nil {
                args += ["--transcript", f.path]
            }
        } else if let t = j.transcriptURL {
            args += ["--transcript", t.path]
        }

        // A second recording of the same meeting: notetaker lines the two up on
        // their words and also writes transcript_merged.md + disagreements.md.
        if let second = j.secondURL { args += ["--second", second.path] }

        let proc = Process()
        proc.executableURL = URL(fileURLWithPath: "/bin/bash")
        proc.arguments = args
        proc.environment = env

        let pipe = Pipe()
        proc.standardOutput = pipe
        proc.standardError = pipe
        pipe.fileHandleForReading.readabilityHandler = { [weak j] handle in
            let data = handle.availableData
            guard !data.isEmpty else { return }
            let chunk = String(decoding: data, as: UTF8.self)   // never drop a chunk over one bad byte
            Task { @MainActor in j?.append(chunk) }
        }
        // Drain what is still in the pipe before judging the run: the last chunk,
        // with OUT_DIR=, can arrive after the process has exited.
        proc.terminationHandler = { [weak j] p in
            pipe.fileHandleForReading.readabilityHandler = nil
            let tail = String(decoding: pipe.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
            Task { @MainActor in
                if !tail.isEmpty { j?.append(tail) }
                JobQueue.shared.finished(status: p.terminationStatus)
            }
        }

        self.task = proc
        j.appendLine("▶ processing \(audio.lastPathComponent)…\n")
        do {
            try proc.run()
        } catch {
            j.appendLine("✗ failed to launch: \(error.localizedDescription)")
            pipe.fileHandleForReading.readabilityHandler = nil
            task = nil
            current = nil
            j.status = .failed(status: -1)
            startNextIfIdle()
        }
    }

    /// Stop the running job: SIGTERM the whole process tree (bash → python →
    /// speech/ffmpeg/claude), since terminating just the bash parent would leave
    /// the heavy `speech` child running. The queue pauses; Resume carries on.
    func stop() {
        guard let p = task, let j = current else { return }
        stopped = true
        paused = true
        j.appendLine("\n⏹ stopping…")
        Self.killTree(pid: p.processIdentifier)
        p.terminate()
    }

    private static func killTree(pid: Int32) {
        let pgrep = Process()
        pgrep.executableURL = URL(fileURLWithPath: "/usr/bin/pgrep")
        pgrep.arguments = ["-P", "\(pid)"]
        let pipe = Pipe(); pgrep.standardOutput = pipe
        try? pgrep.run(); pgrep.waitUntilExit()
        let out = String(data: pipe.fileHandleForReading.readDataToEndOfFile(),
                         encoding: .utf8) ?? ""
        for line in out.split(separator: "\n") {
            if let child = Int32(line.trimmingCharacters(in: .whitespaces)) {
                killTree(pid: child)
            }
        }
        kill(pid, SIGTERM)
    }

    private func finished(status: Int32) {
        task = nil
        guard let j = current else { return }
        current = nil
        if stopped {
            j.status = .stopped
            j.appendLine("\n⏹ stopped.")
        } else if status == 0, let out = Self.parseOutDir(j.log) {
            j.status = .done(outDir: out)
            j.appendLine("\n✓ done — opening \(out)")
            Self.reveal(out)
        } else {
            j.status = .failed(status: status)
            j.appendLine("\n✗ pipeline exited with status \(status)")
        }
        startNextIfIdle()
    }

    /// process.sh prints `OUT_DIR=/abs/path` as its last line.
    private static func parseOutDir(_ log: String) -> String? {
        for line in log.split(separator: "\n").reversed() where line.hasPrefix("OUT_DIR=") {
            return String(line.dropFirst("OUT_DIR=".count))
        }
        return nil
    }

    static func reveal(_ outDir: String) {
        let notes = outDir + "/notes.md"
        if FileManager.default.fileExists(atPath: notes) {
            NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: notes)])
            NSWorkspace.shared.open(URL(fileURLWithPath: notes))
        } else {
            NSWorkspace.shared.activateFileViewerSelecting([URL(fileURLWithPath: outDir)])
        }
    }
}

// MARK: - Voice note: say the context instead of typing it

/// The mic in the context box. Records the Mac's microphone to a 16 kHz WAV,
/// transcribes it on-device with the same `speech` binary and ASR model the
/// pipeline uses, and hands back the text. macOS Dictation is not involved
/// (Tom has it off), and nothing leaves the Mac.
@MainActor
final class VoiceNote: ObservableObject {
    enum State { case idle, starting, recording, transcribing }
    @Published var state: State = .idle
    @Published var problem: String?

    private var recorder: AVAudioRecorder?
    private var stopWhenStarted = false   // released before the mic was ready
    private var onText: ((String) -> Void)?
    private var model = "1.7B", language = ""

    private var file: URL {
        let dir = FileManager.default.temporaryDirectory
            .appendingPathComponent("DropMemo", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("voice-note.wav")
    }

    func start(model: String, language: String, onText: @escaping (String) -> Void) {
        guard state == .idle else { return }
        self.model = model; self.language = language; self.onText = onText
        state = .starting
        stopWhenStarted = false
        problem = nil
        AVCaptureDevice.requestAccess(for: .audio) { granted in
            Task { @MainActor in self.begin(granted: granted) }
        }
    }

    private func begin(granted: Bool) {
        guard granted else {
            state = .idle
            problem = "Microphone access is off for DropMemo: System Settings → Privacy & Security → Microphone."
            return
        }
        let settings: [String: Any] = [
            AVFormatIDKey: kAudioFormatLinearPCM,
            AVSampleRateKey: 16_000,
            AVNumberOfChannelsKey: 1,
            AVLinearPCMBitDepthKey: 16,
            AVLinearPCMIsFloatKey: false,
            AVLinearPCMIsBigEndianKey: false,
        ]
        do {
            let r = try AVAudioRecorder(url: file, settings: settings)
            guard r.record() else { throw NSError(domain: "DropMemo", code: 1) }
            recorder = r
            state = .recording
            if stopWhenStarted { stop() }
        } catch {
            state = .idle
            problem = "Couldn't start the microphone: \(error.localizedDescription)"
        }
    }

    func stop() {
        if state == .starting { stopWhenStarted = true; return }
        guard state == .recording, let r = recorder else { return }
        r.stop()
        recorder = nil
        state = .transcribing
        JobQueue.shared.voiceNoteBusy = true
        let (wav, model, language) = (file, model, language)
        Task.detached {
            let result = VoiceNote.transcribe(wav, model: model, language: language)
            try? FileManager.default.removeItem(at: wav)
            await MainActor.run {
                self.state = .idle
                JobQueue.shared.voiceNoteBusy = false
                switch result {
                case .success(let text) where !text.isEmpty: self.onText?(text)
                case .success: self.problem = "Didn't catch anything; try again a little closer."
                case .failure(let e): self.problem = e.message
                }
            }
        }
    }

    struct Failure: Error { let message: String }

    /// `speech transcribe` prints progress, then "Result: <text>".
    nonisolated static func transcribe(_ wav: URL, model: String,
                                       language: String) -> Result<String, Failure> {
        let proc = Process()
        proc.executableURL = URL(fileURLWithPath: "/usr/bin/env")
        var args = ["speech", "transcribe", wav.path, "--model", model]
        let lang = language.trimmingCharacters(in: .whitespaces)
        if !lang.isEmpty { args += ["--language", lang] }
        proc.arguments = args
        // A GUI app gets the bare PATH; process.sh does the same for the pipeline.
        var env = ProcessInfo.processInfo.environment
        env["PATH"] = "/opt/homebrew/bin:/usr/local/bin:" + (env["PATH"] ?? "/usr/bin:/bin")
        proc.environment = env
        let pipe = Pipe()
        proc.standardOutput = pipe
        proc.standardError = pipe
        do { try proc.run() } catch {
            return .failure(Failure(message: "Couldn't run `speech`: \(error.localizedDescription)"))
        }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        proc.waitUntilExit()
        let out = String(data: data, encoding: .utf8) ?? ""
        if let line = out.components(separatedBy: "\n").last(where: { $0.hasPrefix("Result:") }) {
            return .success(String(line.dropFirst("Result:".count))
                .trimmingCharacters(in: .whitespaces))
        }
        return .failure(Failure(message: "Transcription failed: "
            + (out.components(separatedBy: "\n").last(where: { !$0.isEmpty }) ?? "no output")))
    }
}

/// Click to start and click again to stop, or hold it and talk, letting go to stop.
struct VoiceNoteButton: View {
    @ObservedObject var note: VoiceNote
    var blocked = false
    let start: () -> Void
    @State private var pressedAt: Date?
    @State private var startedThisPress = false

    var body: some View {
        Group {
            switch note.state {
            case .transcribing:
                ProgressView().controlSize(.small)
            default:
                Image(systemName: note.state == .idle ? "mic.fill" : "stop.circle.fill")
                    .font(.system(size: 15))
                    .foregroundColor(note.state == .idle ? .secondary : .red)
            }
        }
        .frame(width: 26, height: 26)
        .contentShape(Rectangle())
        .gesture(DragGesture(minimumDistance: 0)
            .onChanged { _ in
                guard pressedAt == nil else { return }
                pressedAt = Date()
                startedThisPress = note.state == .idle
                if startedThisPress { start() } else { note.stop() }
            }
            .onEnded { _ in
                let held = Date().timeIntervalSince(pressedAt ?? Date())
                pressedAt = nil
                if startedThisPress && held > 0.5 { note.stop() }   // hold to talk
            })
        .help(blocked && note.state == .idle
              ? "The mic is off while a memo is processing: it would load a second speech model."
              : note.state == .idle
              ? "Say the context: click to start and again to stop, or hold while you talk."
              : "Stop and transcribe")
        .disabled(note.state == .transcribing || (blocked && note.state == .idle))
    }
}

